const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = {};
vm.createContext(context);
vm.runInContext(fs.readFileSync('static/answer-format.js', 'utf8'), context);
const render = context.fmtAnswer;
assert.equal(render('结论：目前资料不足[资料1]。\n\n处理步骤：\n1. 核对采集时间。\n2. 比对本机值。'),
  '<h3>结论</h3><p>目前资料不足[资料1]。</p><h3>处理步骤</h3><ol start="1"><li>核对采集时间。</li><li>比对本机值。</li></ol>');
const grouped = render('根据资料整理如下：\n\n1. **组串容量配置问题**\n- 核对配置。\n- **解决方法**：按实际容量填写。\n\n2. **采集连接异常**\n- 核对连接。');
assert(grouped.includes('<strong>组串容量配置问题</strong>'));
assert(grouped.includes('<strong>解决方法</strong>：按实际容量填写。'));
assert(grouped.includes('<ol start="2">'));
assert(!grouped.includes('**'));
assert.equal(render('### 初步判断\n\n说明文字。'), '<h3>初步判断</h3><p>说明文字。</p>');
assert.equal(render('###结论\n正文'), '<h3>结论</h3><p>正文</p>');
assert.equal(render('**### 结论**\n正文'), '<h3>结论</h3><p>正文</p>');
assert.equal(render('**结论**\n正文'), '<h3>结论</h3><p>正文</p>');
assert.equal(render('**下一步**\n请补充信息。'), '<h3>下一步</h3><p>请补充信息。</p>');
assert.equal(render('400 V'), '<p>400 V</p>');
assert.equal(render('1.2 kV'), '<p>1.2 kV</p>');
assert.equal(render('192.168.1.2'), '<p>192.168.1.2</p>');
assert.equal(render('### C#'), '<h3>C#</h3>');
assert(render('1. 第一步\n3. 第三步').includes('<li value="3">'));
assert.equal(render('电压：400 V'), '<p>电压：400 V</p>');
assert.equal(render('**正确**，原因如下。'), '<p><strong>正确</strong>，原因如下。</p>');
const unsafe = render('### <img src=x onerror=alert(1)>\n<script>alert(1)</script>\n\n`<svg onload=alert(1)>`');
assert(!unsafe.includes('<img') && !unsafe.includes('<script') && !unsafe.includes('<svg'));
const code = render('```text\n**保持原样** <tag>\n```');
assert.equal(code, '<pre><code>**保持原样** &lt;tag&gt;</code></pre>');
assert(render('| 项目 | 数值 |\n| --- | --- |\n| 电压 | 400 V |').includes('<td>400 V</td>'));
assert(render('未关闭代码块\n```\n<tag>').includes('&lt;tag&gt;'));
assert.equal(render(null), '');
const html = fs.readFileSync('static/index.html', 'utf8');
assert(html.includes("fmtAnswer(payload.answer || '')"));
assert(html.includes("fmtAnswer(payload.explanation || '')"));
assert(html.indexOf('answer-format.js') < html.indexOf('const state ='));
assert(html.includes('.answer-content h3 { color: #1f2937;'));
assert(html.includes('.answer-content { color: #4b5563;'));
console.log('普通文字、Markdown、题目讲解、表格代码与HTML转义：全部通过');
